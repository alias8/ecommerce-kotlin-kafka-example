-- report_job.status and shipping.status are plain (non-@Enumerated(STRING)) enums,
-- so Hibernate persists them by ordinal (smallint), not name.
CREATE TABLE public.report_job (
    id bigint NOT NULL,
    customer_email character varying(255),
    status smallint,
    requested_at timestamp(6) with time zone,
    completed_at timestamp(6) with time zone,
    result_path character varying(255),
    CONSTRAINT report_job_pkey PRIMARY KEY (id),
    CONSTRAINT report_job_status_check CHECK (((status >= 0) AND (status <= 3)))
);

ALTER TABLE public.report_job ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.report_job_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

