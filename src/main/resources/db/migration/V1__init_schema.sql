-- Baseline schema, captured from Hibernate's own DDL generation (ddl-auto=create
-- against a scratch Postgres instance) so the columns/types/constraints here are
-- guaranteed to match what each @Entity actually expects under ddl-auto=validate.

CREATE TABLE public.users (
    id character varying(255) NOT NULL,
    email character varying(255) NOT NULL,
    password_hash character varying(255) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT users_email_key UNIQUE (email)
);

CREATE TABLE public.inventory (
    sku_id character varying(255) NOT NULL,
    stock_level integer NOT NULL,
    CONSTRAINT inventory_pkey PRIMARY KEY (sku_id)
);

CREATE TABLE public.orders (
    order_id bigint NOT NULL,
    customer_email character varying(255),
    payment_token character varying(255),
    reservation_id character varying(255),
    status character varying(255),
    CONSTRAINT orders_pkey PRIMARY KEY (order_id),
    CONSTRAINT orders_status_check CHECK (((status)::text = ANY ((ARRAY['PENDING'::character varying, 'PAID'::character varying, 'SHIPPED'::character varying, 'DELIVERED'::character varying])::text[])))
);

ALTER TABLE public.orders ALTER COLUMN order_id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.orders_order_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.cart_item (
    id bigint NOT NULL,
    quantity integer NOT NULL,
    unit_price double precision NOT NULL,
    sku_id character varying(255),
    product_id character varying(255),
    order_id bigint,
    CONSTRAINT cart_item_pkey PRIMARY KEY (id),
    CONSTRAINT fk_cart_item_order FOREIGN KEY (order_id) REFERENCES public.orders(order_id)
);

ALTER TABLE public.cart_item ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.cart_item_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

CREATE TABLE public.payment (
    id bigint NOT NULL,
    order_id bigint NOT NULL,
    total_price double precision NOT NULL,
    payment_token character varying(255),
    success boolean NOT NULL,
    CONSTRAINT payment_pkey PRIMARY KEY (id)
);

ALTER TABLE public.payment ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
