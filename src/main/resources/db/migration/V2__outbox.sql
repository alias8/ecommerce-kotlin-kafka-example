-- Transactional outbox: a message to publish, written in the SAME transaction as the
-- business row (e.g. report_job). Both commit or neither does, so a crash can't leave
-- a job with no message. OutboxRelay publishes unsent rows to the broker.
CREATE TABLE public.outbox (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_key    character varying(255) NOT NULL UNIQUE,  -- deterministic, e.g. 'report:42'; also the idempotency key
    type       character varying(50)  NOT NULL,         -- which queue/routing key, e.g. 'report'
    payload    text                   NOT NULL,         -- JSON message body
    created_at timestamp(6) with time zone NOT NULL DEFAULT now(),
    sent_at    timestamp(6) with time zone              -- NULL until the relay has published it
);

-- The relay only ever looks for unsent rows, oldest first.
CREATE INDEX outbox_unsent_idx ON public.outbox (id) WHERE sent_at IS NULL;
